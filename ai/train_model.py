"""
Train the click-prediction model on the synthetic feature dataset and save it.

The model is fitted on ALL rows: generalisation was already measured with
ai/evaluate_splits.py (chronological and unseen-employee splits). Do not
evaluate this saved model on the same CSV; it has seen every row.

Run from the project root:  python -m ai.train_model
"""

import json
import os
from datetime import datetime, timezone

import joblib
import pandas as pd
import sklearn

from ai.model_config import (
    DATA_FILE,
    FEATURES,
    METADATA_FILE,
    MODEL_FILE,
    TARGET,
    build_pipeline,
)

MODEL_VERSION = "rf-synthetic-v2"


def load_dataset():
    dataset = pd.read_csv(DATA_FILE)

    print("Dataset loaded successfully.")
    print(f"Rows: {len(dataset)}")
    print(f"Columns: {len(dataset.columns)}")

    return dataset


def train_model():
    dataset = load_dataset()

    X = dataset[FEATURES]
    y = dataset[TARGET]

    print()
    print("Features:")
    print(FEATURES)
    print(f"Target: {TARGET}  (click rate in data: {y.mean():.3f})")

    pipeline = build_pipeline()

    print()
    print("Training Random Forest model on all rows...")
    pipeline.fit(X, y)
    print("Model training completed.")

    os.makedirs(os.path.dirname(MODEL_FILE), exist_ok=True)
    joblib.dump(pipeline, MODEL_FILE)

    # Metadata travels with the model so the API can report exactly which
    # model produced a prediction, and refuse a mismatched feature set.
    metadata = {
        "model_version": MODEL_VERSION,
        "trained_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "training_rows": int(len(dataset)),
        "training_click_rate": round(float(y.mean()), 4),
        "features": FEATURES,
        "target": TARGET,
        "sklearn_version": sklearn.__version__,
        "data_source": "SYNTHETIC (ML Synthetic Training Dataset v1)",
        "status": "experimental",
        "note": (
            "Trained on synthetic data generated by our own probability rules. "
            "Evaluation (ai/evaluate_splits.py) does not show real-world accuracy."
        ),
    }

    with open(METADATA_FILE, "w", encoding="utf-8") as file:
        json.dump(metadata, file, indent=2)

    print()
    print("Model saved successfully.")
    print(f"Model path:    {MODEL_FILE}")
    print(f"Metadata path: {METADATA_FILE}")
    print(f"Model version: {MODEL_VERSION}")


if __name__ == "__main__":
    train_model()
