"""
Honest evaluation of the click-prediction model on SYNTHETIC data.

Two different questions, two different splits:

Q1 (known employees, future): train on each employee's first N simulations,
    test on their later ones. Test-row features use the full prior history,
    exactly as they would in production.

Q2 (unseen employees): GroupKFold by employee_id, so the model is tested on
    employees it never saw during training.

Each result is compared with simple baselines. A model that cannot beat
"predict the overall click rate" or "use only the employee's past click rate"
has learned nothing useful.

NOTE: the data is synthetic, generated by our own probability rules, with
only 12 employee profiles. None of these numbers show real-world accuracy.
"""

import numpy as np
import pandas as pd
from sklearn.metrics import (
    average_precision_score,
    brier_score_loss,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.model_selection import GroupKFold

# Evaluation only: the generator's hidden click probability is used as an
# upper-bound reference. It is NEVER a model feature.
from ai.data_generation.generate_training_data import calculate_click_probability
from ai.model_config import (  # noqa: F401  (CATEGORICAL/NUMERICAL re-exported)
    CATEGORICAL,
    DATA_FILE,
    FEATURES,
    NUMERICAL,
    TARGET,
    build_pipeline,
)

TRAIN_FRACTION = 0.8  # Q1: each employee's first 80% train, last 20% test


def report(name, y_true, scores, threshold=0.5):
    """Print ranking metrics (AUC) and thresholded metrics for one scorer."""
    y_pred = (scores >= threshold).astype(int)
    print(
        f"  {name:<34} "
        f"AUC={roc_auc_score(y_true, scores):.3f}  "
        f"AP={average_precision_score(y_true, scores):.3f}  "
        f"Brier={brier_score_loss(y_true, np.clip(scores, 0, 1)):.3f}"
    )
    return y_pred


def run_comparison(title, train_df, test_df, scores_model):
    y_test = test_df[TARGET].to_numpy()
    base_rate = train_df[TARGET].mean()

    print(f"\n=== {title} ===")
    print(
        f"  train rows={len(train_df)}  test rows={len(test_df)}  "
        f"test click rate={y_test.mean():.3f}  (AP of a random scorer ~ that rate)"
    )

    report("Baseline: constant train rate", y_test, np.full(len(test_df), base_rate))
    report("Baseline: employee past click_rate", y_test, test_df["click_rate"].to_numpy())
    y_pred = report("Random Forest", y_test, scores_model, threshold=base_rate)

    oracle = np.array(
        [
            calculate_click_probability(e, p)
            for e, p in zip(test_df["employee_id"], test_df["phishing_type"])
        ]
    )
    report("Ceiling: hidden generator prob.", y_test, oracle)

    print(
        f"\n  Random Forest at threshold = train click rate ({base_rate:.2f}): "
        f"precision={precision_score(y_test, y_pred, zero_division=0):.2f}  "
        f"recall={recall_score(y_test, y_pred):.2f}  "
        f"F1={f1_score(y_test, y_pred):.2f}"
    )
    print("  Confusion matrix [[TN FP] [FN TP]]:")
    print("  " + str(confusion_matrix(y_test, y_pred)).replace("\n", "\n  "))


def question_1(data):
    # total_simulations = index of the row within the employee's history.
    cutoff = int(TRAIN_FRACTION * (data["total_simulations"].max() + 1))
    train_df = data[data["total_simulations"] < cutoff]
    test_df = data[data["total_simulations"] >= cutoff]

    pipeline = build_pipeline()
    pipeline.fit(train_df[FEATURES], train_df[TARGET])
    scores = pipeline.predict_proba(test_df[FEATURES])[:, 1]

    run_comparison(
        "Q1: known employees, later simulations (chronological split)",
        train_df,
        test_df,
        scores,
    )


def question_2(data):
    groups = data["employee_id"]
    scores = np.zeros(len(data))

    for train_idx, test_idx in GroupKFold(n_splits=4).split(data, groups=groups):
        pipeline = build_pipeline()
        pipeline.fit(data.iloc[train_idx][FEATURES], data.iloc[train_idx][TARGET])
        scores[test_idx] = pipeline.predict_proba(data.iloc[test_idx][FEATURES])[:, 1]

    run_comparison(
        "Q2: unseen employees (GroupKFold by employee_id, pooled)",
        data,
        data,
        scores,
    )


def main():
    data = pd.read_csv(DATA_FILE)
    # Chronological order within each employee is encoded by total_simulations
    # (= number of earlier simulations for that employee).
    print(f"Rows: {len(data)}  employees: {data['employee_id'].nunique()}")
    print(f"Overall click rate: {data[TARGET].mean():.3f}  (clicks: {int(data[TARGET].sum())})")
    print("SYNTHETIC DATA: results do not show real-world accuracy.")

    question_1(data)
    question_2(data)


if __name__ == "__main__":
    main()
